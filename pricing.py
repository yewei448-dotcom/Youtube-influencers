def 查报价区间(合作形式, 国家, 观看数):
    """根据合作形式 + 国家 + 观看数，返回 (最低报价, 最高报价)。找不到返回 None。"""
    table = 合作形式映射.get(合作形式)
    if not table:
        return None
    group = 国家映射.get(国家, 国家)
    rows = table.get(group)
    if not rows:
        return None
    # 找观看数落在哪个档位
    for lo, hi, plo, phi in rows:
        if lo <= 观看数 < hi:
            return (plo, phi)
    return None

def 评估报价(合作形式, 国家, 观看数, 对方报价):
    """
    评估对方报价，给出结论 + 最佳价格（建议砍到的目标价）。
    不直接拒绝，超出预算时都建议砍价。
    返回 dict: {结论, 最佳价格, 建议价格区间, 建议动作, 说明}
    结论: 可接受 / 可砍价
    """
    rng = 查报价区间(合作形式, 国家, 观看数)
    if rng is None:
        return {
            "结论": "无参考价",
            "最佳价格": None,
            "建议价格区间": None,
            "建议动作": "人工判断",
            "说明": f"报价表里没有「{合作形式} / {国家} / 观看数 {观看数}」的档位，请人工判断",
        }
    plo, phi = rng
    # 特殊规则：均播非常高（≥2万）且报价超200，用CPM算合理价，提醒慎重
    if 观看数 >= 20000 and 对方报价 > 200:
        cpm_lo = round(观看数 / 1000 * 10)
        cpm_hi = round(观看数 / 1000 * 15)
        合理价 = round(观看数 / 1000 * 12.5)
        return {
            "结论": "需慎重",
            "最佳价格": 合理价,
            "建议价格区间": (cpm_lo, cpm_hi),
            "建议动作": "慎重考虑",
            "说明": f"均播 {观看数} 非常高、报价 ${对方报价} 超过 $200（报价表无此档参考）。按 CPM≤10~15 估算，合理价约 ${cpm_lo}~${cpm_hi}，请慎重考虑后再决定",
        }
    if 对方报价 <= phi:
        结论 = "可接受"
        最佳价格 = 对方报价
        动作 = "接受"
        说明 = f"对方报价 ${对方报价} 在报价区间 ${plo}~${phi} 内，可直接接受"
    else:
        结论 = "可砍价"
        最佳价格 = phi
        动作 = "砍价"
        说明 = f"对方报价 ${对方报价} 高于上限 ${phi}，建议砍到 ${phi}（区间 ${plo}~${phi}）"
    return {
        "结论": 结论,
        "最佳价格": 最佳价格,
        "建议价格区间": (plo, phi),
        "建议动作": 动作,
        "说明": 说明,
    }


