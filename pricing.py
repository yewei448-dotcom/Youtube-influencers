def 生成议价回复(结论, name, 最佳价格):
    """根据评估结论（可接受/可砍价）生成回复邮件，替换 {name} 和 {最佳价格}"""
    key = {"可接受": "接受", "可砍价": "砍价"}.get(结论, 结论)
    t = 议价模板.get(key)
    if not t:
        return None, None
    body = t["body"].replace("{name}", name or "there")
    body = body.replace("{最佳价格}", str(最佳价格) if 最佳价格 is not None else "")
    return t["subject"], body


